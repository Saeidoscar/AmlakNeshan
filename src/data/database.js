// Format price in Persian
export function formatPrice(price) {
  if (!price) return 'توافقی';
  if (price >= 1000000000) {
    const billion = Math.floor(price / 1000000000);
    const million = Math.floor((price % 1000000000) / 1000000);
    if (million === 0) return `${billion} میلیارد تومان`;
    return `${billion} میلیارد و ${million} میلیون تومان`;
  }
  if (price >= 1000000) {
    return `${Math.floor(price / 1000000).toLocaleString('fa-IR')} میلیون تومان`;
  }
  return `${price.toLocaleString('fa-IR')} تومان`;
}

